#!/usr/bin/env python3
"""Compile the built-in shaders for one platform and embed the library.

    python3 tests/build_metallib.py SDK OUTDIR

SDK is macosx, iphoneos or iphonesimulator. Writes OUTDIR/PsychMetalShaderLibrary.h,
which the engine includes: the Metal library compiled from PsychMetalShaders.metal
at build time, as Apple advises, so opening a window loads it instead of
compiling source. The header goes in the build's own directory, never beside the
sources, so a library for one platform cannot be built into another.

Xcode 26 and later ship the Metal compiler as a separate component; if it is
missing, this says how to install it.
"""
from pathlib import Path
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parents[1]
sdk, out = sys.argv[1], Path(sys.argv[2])
minimum = {'macosx': '-mmacosx-version-min=14.0', 'iphoneos': '-mios-version-min=15.0',
           'iphonesimulator': '-mios-simulator-version-min=15.0'}
if sdk not in minimum:
    sys.exit('SDK must be macosx, iphoneos or iphonesimulator.')
with tempfile.TemporaryDirectory() as temp:
    air, library = Path(temp) / 'shaders.air', Path(temp) / 'shaders.metallib'
    compiled = subprocess.run(['xcrun', '-sdk', sdk, 'metal', minimum[sdk], '-c', str(root / 'PsychMetalShaders.metal'),
                               '-o', str(air)], capture_output=True, text=True)
    if compiled.returncode:
        sys.stderr.write(compiled.stderr)
        if 'metal' in compiled.stderr and ('not found' in compiled.stderr or 'unable to find utility' in compiled.stderr
                                           or 'missing Metal Toolchain' in compiled.stderr):
            sys.exit('The Metal compiler is not installed. With Xcode 26 or later, install it with\n'
                     '    xcodebuild -downloadComponent MetalToolchain\nand build again.')
        sys.exit('The built-in shaders did not compile.')
    subprocess.run(['xcrun', '-sdk', sdk, 'metallib', str(air), '-o', str(library)], check=True)
    data = library.read_bytes()
rows = ',\n'.join(','.join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
text = ('// Generated by tests/build_metallib.py for %s; do not edit.\n'
        'static const unsigned char PMMetalLibrary[] = {\n%s\n};\n' % (sdk, rows))
out.mkdir(parents=True, exist_ok=True)
header = out / 'PsychMetalShaderLibrary.h'
header.write_text(text)
print(f'{header}: {len(data)} bytes of Metal library for {sdk}.')
